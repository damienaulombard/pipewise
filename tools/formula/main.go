// Command formula writes the Homebrew formula of a pipewise release from its
// SHA256SUMS, for the release workflow to push to the tap:
//
//	go run ./tools/formula -tag v1.2.3 -sums dist/SHA256SUMS > pipewise.rb
//
// The formula installs the released binaries for macOS and Linux, amd64 and
// arm64; it builds nothing.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"
	"regexp"
	"strings"
	"text/template"
)

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

// run is main without the process: it returns the exit code, 2 for a usage
// error, 1 when no formula can be written.
func run(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("formula", flag.ContinueOnError)
	fs.SetOutput(stderr)
	repo := fs.String("repo", "damienaulombard/pipewise", "GitHub repository that publishes the release")
	tag := fs.String("tag", "", "release tag, vX.Y.Z")
	sums := fs.String("sums", "", "path to the SHA256SUMS of the release")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *tag == "" || *sums == "" {
		return fail(stderr, 2, "-tag and -sums are required")
	}
	data, err := os.ReadFile(*sums)
	if err != nil {
		return fail(stderr, 1, err)
	}
	out, err := generate(*repo, *tag, data)
	if err != nil {
		return fail(stderr, 1, err)
	}
	if _, err := stdout.Write(out); err != nil {
		return fail(stderr, 1, err)
	}
	return 0
}

// fail reports msg on stderr and returns code; there is nowhere left to
// report a failed write to stderr.
func fail(stderr io.Writer, code int, msg any) int {
	_, _ = fmt.Fprintln(stderr, "formula:", msg)
	return code
}

var (
	// Both end up inside Ruby strings: anything else is refused, not escaped.
	tagPattern  = regexp.MustCompile(`^v[0-9]+\.[0-9]+\.[0-9]+$`)
	repoPattern = regexp.MustCompile(`^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$`)
	hashPattern = regexp.MustCompile(`^[0-9a-fA-F]{64}$`)
)

// platforms are the archives the formula installs, in the order of the
// formula: Homebrew picks one with on_macos/on_linux and on_arm/on_intel.
var platforms = []struct{ os, arch string }{
	{"darwin", "arm64"},
	{"darwin", "amd64"},
	{"linux", "arm64"},
	{"linux", "amd64"},
}

type archive struct{ URL, SHA256 string }

var formula = template.Must(template.New("formula").Parse(`# Generated by tools/formula in {{.Repo}} for {{.Tag}}. Do not edit:
# the next release overwrites it.
class Pipewise < Formula
  desc "Find the GitLab CI jobs that run more often than they need to"
  homepage "https://github.com/{{.Repo}}"
  version "{{.Version}}"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "{{(index .Archives 0).URL}}"
      sha256 "{{(index .Archives 0).SHA256}}"
    end
    on_intel do
      url "{{(index .Archives 1).URL}}"
      sha256 "{{(index .Archives 1).SHA256}}"
    end
  end

  on_linux do
    on_arm do
      url "{{(index .Archives 2).URL}}"
      sha256 "{{(index .Archives 2).SHA256}}"
    end
    on_intel do
      url "{{(index .Archives 3).URL}}"
      sha256 "{{(index .Archives 3).SHA256}}"
    end
  end

  def install
    bin.install "pipewise"
  end

  test do
    assert_equal "pipewise v#{version}", shell_output("#{bin}/pipewise version").strip
  end
end
`))

// generate returns the formula for the release tag of repo, with the
// checksums read from sums, the content of its SHA256SUMS.
func generate(repo, tag string, sums []byte) ([]byte, error) {
	if !tagPattern.MatchString(tag) {
		return nil, fmt.Errorf("tag %q: want vX.Y.Z", tag)
	}
	if !repoPattern.MatchString(repo) {
		return nil, fmt.Errorf("repository %q: want owner/name", repo)
	}
	checksums, err := parseSums(sums)
	if err != nil {
		return nil, err
	}
	archives := make([]archive, len(platforms))
	for i, p := range platforms {
		name := fmt.Sprintf("pipewise_%s_%s_%s.tar.gz", tag, p.os, p.arch)
		sum, ok := checksums[name]
		if !ok {
			return nil, fmt.Errorf("SHA256SUMS has no checksum for %s", name)
		}
		archives[i] = archive{
			URL:    fmt.Sprintf("https://github.com/%s/releases/download/%s/%s", repo, tag, name),
			SHA256: strings.ToLower(sum),
		}
	}
	var out bytes.Buffer
	err = formula.Execute(&out, struct {
		Repo, Tag, Version string
		Archives           []archive
	}{repo, tag, strings.TrimPrefix(tag, "v"), archives})
	return out.Bytes(), err
}

// parseSums reads the output of shasum -a 256: one "<hash>  <file>" per line,
// or "<hash> *<file>" in binary mode.
func parseSums(sums []byte) (map[string]string, error) {
	checksums := map[string]string{}
	sc := bufio.NewScanner(bytes.NewReader(sums))
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimRight(sc.Text(), "\r")
		if strings.TrimSpace(line) == "" {
			continue
		}
		sum, name, ok := strings.Cut(line, " ")
		name = strings.TrimPrefix(strings.TrimPrefix(name, " "), "*")
		if !ok || name == "" || !hashPattern.MatchString(sum) {
			return nil, fmt.Errorf("SHA256SUMS line %d: want \"<sha256>  <file>\", got %q", n, line)
		}
		if _, dup := checksums[name]; dup {
			return nil, fmt.Errorf("SHA256SUMS line %d: %s listed twice", n, name)
		}
		checksums[name] = sum
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("SHA256SUMS: %w", err)
	}
	return checksums, nil
}
